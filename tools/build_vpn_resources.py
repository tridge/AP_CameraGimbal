#!/usr/bin/env python3
"""Verify pinned VPN tools and embed them for lazy extraction to tmpfs."""
import argparse
import hashlib
import json
import lzma
import os
import tempfile
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def resources(directory):
    manifest=json.loads((directory/'manifest.json').read_text())
    result={}
    for name in ('zerotier-one','tun.ko'):
        # The pins are reviewed in the repository, never supplied by the camera.
        item=manifest['files'][name]
        with lzma.open(directory/(name+'.xz')) as source:
            data=source.read(4*1024*1024+1)
        if len(data)!=item['size'] or hashlib.sha256(data).hexdigest()!=item['sha256']:
            raise ValueError('VPN tool checksum mismatch: '+str(directory/name))
        result[name]=data
    return manifest,result

def build(source,output):
    pieces=['// Generated by tools/build_vpn_resources.py; do not edit.\n#pragma once\n']
    for index,target in enumerate(('mt11','zt30')):
        manifest,data=resources(source/target)
        pieces.append(('#if' if index==0 else '#elif')+f' APCAM_TARGET == APCAM_TARGET_{target.upper()}\n')
        for name,symbol in [('zerotier-one','vpn_client'),('tun.ko','vpn_tun')]:
            pieces.append(f'static const unsigned char {symbol}[] = {{\n')
            b=data[name]
            pieces.extend(','.join(str(v) for v in b[i:i+32])+',\n' for i in range(0,len(b),32))
            pieces.append('};\n')
        pieces.append(f'static const char vpn_kernel_device[] = {json.dumps(manifest["kernel_device"])};\n')
        pieces.append(f'static const unsigned long long vpn_kernel_offset = {manifest["kernel_offset"]}ULL;\n')
        pieces.append(f'static const unsigned long long vpn_kernel_size = {manifest["kernel_size"]}ULL;\n')
        pieces.append(f'static const char vpn_kernel_hash[] = {json.dumps(manifest["kernel_sha256"])};\n')
    pieces.append('#endif\n')
    content=''.join(pieces)
    output.parent.mkdir(parents=True,exist_ok=True)
    if not output.exists() or output.read_text()!=content:
        temporary=None
        try:
            with tempfile.NamedTemporaryFile(mode='w',dir=output.parent,prefix='.'+output.name+'.',delete=False) as out:
                temporary=out.name;out.write(content);out.flush();os.fsync(out.fileno())
            os.replace(temporary,output);temporary=None
        finally:
            if temporary:os.unlink(temporary)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=ROOT/'packaging/vpn')
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args();build(args.source,args.output)
